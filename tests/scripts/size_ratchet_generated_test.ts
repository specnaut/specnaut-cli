// cli#798: the ratchet leaves generated code out with no `exempt:` entry, and
// prints every file it left out that way. Each case plants a file over the
// ceiling (500), so a file the ratchet did not leave out is refused by name,
// and a file it did is named on a `generated:` line only that path prints.

import { assert, assertEquals, assertStringIncludes } from "@std/assert";
import { dirname, join } from "@std/path";
import { EXEMPT, FILE, lines, ratchet, repo, run } from "./size_ratchet_fixture.ts";

const MARKER = "// Code Generated by a tool. DO NOT EDIT.\n";
const CONFIG = FILE(200, 500);

/** Writes `path` and stages it. */
async function put(dir: string, path: string, text: string): Promise<void> {
  await Deno.mkdir(dirname(join(dir, path)), { recursive: true });
  await Deno.writeTextFile(join(dir, path), text);
  await run("git", ["add", "--", path], dir);
}

/** A repo with `path` committed holding `text`. */
async function committed(path: string, text: string, config = CONFIG): Promise<string> {
  const dir = await repo(10, config);
  await put(dir, path, text);
  await run("git", ["commit", "-q", "-m", "add"], dir);
  return dir;
}

async function passes(dir: string, ...said: string[]): Promise<void> {
  const r = await ratchet(dir);
  assertEquals(r.code, 0, r.stdout + r.stderr);
  for (const line of said) assertStringIncludes(r.stdout, `  generated: ${line}\n`);
}

async function refused(dir: string, ...refusals: string[]): Promise<string> {
  const r = await ratchet(dir);
  assertEquals(r.code, 1, r.stdout + r.stderr);
  for (const line of refusals) assertStringIncludes(r.stderr, line);
  return r.stdout;
}

const over = (path: string, before: number, after: number) =>
  `${path}: ${before} → ${after} (target 200, ceiling 500) — over the ceiling`;

Deno.test("a new file under a generated name passes, and is named as generated", async () => {
  const dir = await repo(10, CONFIG);
  const names = ["src/_generated/api.ts", "src/api.gen.ts", "web/package-lock.json", "Cargo.lock"];
  for (const name of names) await put(dir, name, lines(600));
  await passes(dir, ...names.map((n) => `${n} (path convention)`));
});

Deno.test("a new file with a header marker passes, on line 5 and up to byte 8000", async () => {
  const dir = await repo(10, CONFIG);
  await put(dir, "src/schema.ts", MARKER + lines(600));
  await put(dir, "src/fifth.ts", lines(4) + MARKER + lines(600));
  await put(
    dir,
    "src/edge.ts",
    "x".repeat(8000 - "@generated".length) + "@generated\n" + lines(600),
  );
  await passes(
    dir,
    "src/schema.ts (header marker, new file)",
    "src/fifth.ts (header marker, new file)",
    "src/edge.ts (header marker, new file)",
  );
});

Deno.test("a marker past line 5, or past byte 8000, is not a header", async () => {
  const dir = await repo(10, CONFIG);
  await put(dir, "src/late.ts", lines(5) + MARKER + lines(600));
  await put(
    dir,
    "src/far.ts",
    "x".repeat(8001 - "@generated".length) + "@generated\n" + lines(600),
  );
  await refused(dir, over("src/late.ts", 0, 606), over("src/far.ts", 0, 601));
});

Deno.test("'do not edit' alone does not exempt a file", async () => {
  const dir = await repo(10, CONFIG);
  await put(dir, "src/hand.ts", "// DO NOT EDIT without a review\n" + lines(600));
  await refused(dir, over("src/hand.ts", 0, 601));
});

Deno.test("a marker added to a file the base held unmarked is measured, and said so", async () => {
  const dir = await committed("src/old.ts", lines(450));
  await put(dir, "src/old.ts", MARKER + lines(600));
  const stdout = await refused(dir, over("src/old.ts", 450, 601));
  assertStringIncludes(stdout, "  generated: src/old.ts (header marker added - measured)\n");
});

Deno.test("a marker the base already carried keeps the file out", async () => {
  const dir = await committed("src/old.ts", MARKER + lines(450));
  await put(dir, "src/old.ts", MARKER + lines(600));
  await passes(dir, "src/old.ts (header marker, already at the base)");
});

Deno.test("a file the base held under a generated name stays generated as it grows", async () => {
  const dir = await committed("src/api.gen.ts", lines(450));
  await put(dir, "src/api.gen.ts", lines(600));
  await passes(dir, "src/api.gen.ts (path convention)");
});

Deno.test("a rename into a generated name is judged by its old name: measured", async () => {
  const dir = await committed("src/api.ts", lines(450));
  await run("git", ["mv", "src/api.ts", "src/api.gen.ts"], dir);
  await put(dir, "src/api.gen.ts", lines(600));
  await refused(dir, over("src/api.gen.ts", 450, 600));
});

Deno.test("a `!` entry keeps a generated name and a generated header measured", async () => {
  const dir = await repo(10, CONFIG + EXEMPT("!src/api.gen.ts", "!src/schema.ts"));
  await put(dir, "src/api.gen.ts", lines(600));
  await put(dir, "src/schema.ts", MARKER + lines(600));
  await put(dir, "src/other.gen.ts", lines(600));
  const stdout = await refused(dir, over("src/api.gen.ts", 0, 600), over("src/schema.ts", 0, 601));
  assertStringIncludes(stdout, "  generated: src/other.gen.ts (path convention)\n");
});

Deno.test("a positive `exempt:` glob still exempts a file a `!` entry names", async () => {
  const dir = await repo(10, CONFIG + EXEMPT("src/*", "!src/api.gen.ts", "!src/x.ts"));
  await put(dir, "src/api.gen.ts", lines(600));
  await put(dir, "src/x.ts", lines(600));
  const r = await ratchet(dir);
  assertEquals(r.code, 0, r.stdout + r.stderr);
  assertStringIncludes(r.stdout, "size-ratchet: 0 staged file(s) within the file limits");
});

Deno.test({
  name: "a name holding a newline is never generated, by name or by header",
  ignore: Deno.build.os === "windows",
  fn: async () => {
    const dir = await repo(10, CONFIG);
    await put(dir, "a\nb.gen.ts", lines(600));
    await put(dir, "c\nd.ts", MARKER + lines(600));
    await refused(dir, over("a\nb.gen.ts", 0, 600), over("c\nd.ts", 0, 601));
  },
});

Deno.test("the constitution is never generated, whatever its header says", async () => {
  const dir = await repo(10, CONFIG);
  await put(dir, "docs/constitution.md", MARKER + lines(150));
  await refused(dir, "docs/constitution.md: 0 → 151 (target 60, ceiling 100)");
});

Deno.test("a marker on a blob of 128 KB and more is read under pipefail", async () => {
  const dir = await repo(10, CONFIG);
  const text = MARKER + lines(16000);
  assert(text.length >= 128 * 1024, "the fixture blob is smaller than a pipe buffer");
  await put(dir, "src/big_schema.ts", text);
  await passes(dir, "src/big_schema.ts (header marker, new file)");
});

Deno.test("a NUL splitting a phrase hides it, and the shell never warns of it", async () => {
  const dir = await repo(10, CONFIG);
  await put(dir, ".gitattributes", "*.ts diff\n");
  await put(dir, "src/split.ts", "// @gener\0ated\n" + lines(600));
  await put(dir, "src/after.ts", "\0// @generated\n" + lines(600));
  const r = await ratchet(dir);
  assertEquals(r.code, 1, r.stdout + r.stderr);
  assertStringIncludes(r.stderr, over("src/split.ts", 0, 601));
  assertStringIncludes(r.stdout, "  generated: src/after.ts (header marker, new file)\n");
  assert(!r.stderr.includes("null byte"), r.stderr);
});
