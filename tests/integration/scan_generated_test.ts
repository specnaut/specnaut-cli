import { assertEquals } from "@std/assert";
import { MAX_TEXT_BYTES } from "../../src/domain/code_units/estimate_units.ts";
import { dispositions, lines, repo, scanJson } from "./scan_fixture.ts";

/**
 * `specnaut scan` leaves generated code out with no `exempt:` entry, counted under its own reason:
 * a generated name before the file is opened, a header marker from the bytes the binary sniff
 * already reads, in both read paths. Every file here is over the ceiling, so a file the scan did
 * not leave out is a finding by name.
 */

const MARKER = "// Code generated by a tool. DO NOT EDIT.\n";

/** Over the 1 MiB read cap, so the file is streamed rather than read whole. */
const streamed = MARKER + lines(Math.ceil(MAX_TEXT_BYTES / 2) + 10);

// deno-lint-ignore no-explicit-any
const findings = (json: any): string[] => json.files.items.map((f: { path: string }) => f.path);

Deno.test("generated names and headers are exempt as `generated`, in both read paths", async () => {
  const dir = await repo({
    ".gitattributes": "forced.ts diff\n",
    "src/_generated/api.ts": lines(900),
    "web/package-lock.json": lines(900),
    "src/schema.ts": MARKER + lines(900),
    "src/huge.ts": streamed,
    "forced.ts": MARKER + lines(900),
    "src/late.ts": lines(5) + MARKER + lines(900),
    "docs/constitution.md": MARKER + lines(150),
  });
  const { result, json } = await scanJson(dir, "--top", "all");
  assertEquals(result.code, 1, result.stderr);
  assertEquals(json.totals.exempt_by.generated, 5);
  assertEquals(findings(json).sort(), ["docs/constitution.md", "src/late.ts"]);
  assertEquals(dispositions(json), { tracked: 8, sum: 8 });
});

Deno.test("a `!` entry keeps a generated name and a generated header measured", async () => {
  const dir = await repo({
    ".specnaut/size-limits.yml": 'exempt:\n  - "!src/api.gen.ts"\n  - "!src/schema.ts"\n' +
      '  - "!src/huge.ts"\n',
    "src/api.gen.ts": lines(900),
    "src/schema.ts": MARKER + lines(900),
    "src/huge.ts": streamed,
    "src/other.gen.ts": lines(900),
  });
  const { result, json } = await scanJson(dir, "--top", "all");
  assertEquals(result.code, 1, result.stderr);
  assertEquals(json.totals.exempt_by.generated, 1);
  assertEquals(findings(json).sort(), ["src/api.gen.ts", "src/huge.ts", "src/schema.ts"]);
});
