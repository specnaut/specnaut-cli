package parity

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

// Harnesses is the declared harness list. A test fails when it disagrees with
// the `--ai` line of the binary's --help, so a harness added to the CLI cannot
// go unexercised here.
var Harnesses = []string{"claude", "cursor", "codex", "copilot", "opencode", "antigravity"}

// Backends is the declared backlog backend list, held to the `--backlog` line
// of --help the same way.
var Backends = []string{"local", "github", "gitlab", "cloud"}

// matrixCommands are the commands every harness × backend pair runs. Each is
// preceded by the init that makes a project to run it in.
var matrixCommands = []string{"init", "upgrade", "check"}

// backendFlags are the non-interactive init flags each backend needs. The
// remote coordinates are invented (`acme/widgets`) and never contacted.
var backendFlags = map[string]string{
	"local":  "--backlog local",
	"github": "--backlog github --backlog-url https://github.com/orgs/acme/projects/1 --backlog-repo acme/widgets",
	"gitlab": "--backlog gitlab --backlog-url https://gitlab.com/acme/widgets",
	"cloud":  "--backlog cloud",
}

// Scenario is one script the harness runs.
type Scenario struct {
	Name string   // the script's base name, as testscript names it
	File string   // the script's path
	Uses []string // the stubs it declares (`# uses: gh cloud`)
}

// MatrixScript is the generated script for one cell of the matrix. Generated,
// not written out per combination, so the matrix has one definition.
func MatrixScript(command, harness, backend string) (name, script string) {
	name = fmt.Sprintf("%s-%s-%s", command, harness, backend)
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by parity/matrix.go: %s × %s × %s\n", command, harness, backend)
	if command == "check" {
		b.WriteString("# uses: gh\n") // check probes `gh --version` and `gh auth status`
	}
	b.WriteString("mkdir project\ncd project\n")
	fmt.Fprintf(&b, "specnaut init --here --no-git --ai %s --scheme semver --spec-backend local %s\n",
		harness, backendFlags[backend])
	switch command {
	case "upgrade":
		b.WriteString("specnaut upgrade\n")
	case "check":
		b.WriteString("specnaut check --project\n")
	}
	return name, b.String()
}

// Scenarios writes the matrix into dir and returns it with every hand-written
// script under testdata, sorted by name.
func Scenarios(dir, testdata string) ([]Scenario, error) {
	out, err := writeMatrix(dir)
	if err != nil {
		return nil, err
	}
	files, err := filepath.Glob(filepath.Join(testdata, "*.txtar"))
	if err != nil {
		return nil, err
	}
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		out = append(out, Scenario{
			Name: strings.TrimSuffix(filepath.Base(f), ".txtar"),
			File: f,
			Uses: parseUses(string(data)),
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// writeMatrix writes one script per command × harness × backend into dir.
func writeMatrix(dir string) ([]Scenario, error) {
	var out []Scenario
	for _, c := range matrixCommands {
		for _, h := range Harnesses {
			for _, bk := range Backends {
				name, script := MatrixScript(c, h, bk)
				file := filepath.Join(dir, name+".txtar")
				if err := os.WriteFile(file, []byte(script), 0o644); err != nil {
					return nil, err
				}
				out = append(out, Scenario{Name: name, File: file, Uses: parseUses(script)})
			}
		}
	}
	return out, nil
}

var usesLine = regexp.MustCompile(`(?m)^# uses:(.*)$`)

// parseUses reads a script's `# uses:` declarations. Only the script part
// counts — a fixture file that happens to hold the phrase does not.
func parseUses(script string) []string {
	if i := strings.Index(script, "\n-- "); i >= 0 {
		script = script[:i]
	}
	var uses []string
	for _, m := range usesLine.FindAllStringSubmatch(script, -1) {
		uses = append(uses, strings.Fields(m[1])...)
	}
	slices.Sort(uses)
	return slices.Compact(uses)
}

var (
	aiLine      = regexp.MustCompile(`(?m)^\s*--ai <name>\s+Target AI harness:\s*(.+)$`)
	backlogLine = regexp.MustCompile(`(?m)^\s*--backlog <name>\s+Backlog backend:\s*(.+)$`)
)

// HelpHarnesses reads the harness list from the `--ai` line of --help.
func HelpHarnesses(help string) ([]string, error) { return helpList(help, aiLine, "--ai") }

// HelpBackends reads the backend list from the first `--backlog` line of
// --help (the init flags; upgrade's line lists only the switch targets).
func HelpBackends(help string) ([]string, error) { return helpList(help, backlogLine, "--backlog") }

func helpList(help string, re *regexp.Regexp, flag string) ([]string, error) {
	m := re.FindStringSubmatch(help)
	if m == nil {
		return nil, fmt.Errorf("--help has no %s line listing its values", flag)
	}
	var out []string
	for _, part := range strings.Split(m[1], "|") {
		word := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(part), "(default)"))
		if word != "" {
			out = append(out, word)
		}
	}
	return out, nil
}
