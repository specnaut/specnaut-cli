// Reads templates/manifest.json + templates/** and emits src/templates_bundle.ts.
// The generated module exports:
//   - TEMPLATES_VERSION: string
//   - CORE_BUNDLE: CoreBundle (from src/domain/core_bundle.ts)
//   - HARNESS_STATIC: Record<harnessKey, Record<destination, TemplateFile>>
//   - RELEASE_HISTORY: ReleaseHistory (from .specnaut/release/history/, cli#759)
// Runtime code reads nothing from disk.

import { fromFileUrl, relative } from "@std/path";
import { fmtLineWidth } from "./bundle-content-field.ts";
import { coreEntry, harnessStatic, staticFilesByHarness } from "./bundle-entries.ts";
import { assertLinkEntries } from "./bundle-link-entries.ts";
import { assertManagedSectionsFenced } from "./bundle-managed-sections.ts";
import { assertAllSourcesPresent, type Manifest, readManifest } from "./bundle-manifest.ts";
import { readReleaseHistory, releaseHistoryEntries } from "./bundle-release-history.ts";

const ROOT = new URL("..", import.meta.url);
const TEMPLATES_DIR = new URL("templates/", ROOT);
const MANIFEST_PATH = new URL("templates/manifest.json", ROOT);
const OUTPUT_PATH = new URL("src/templates_bundle.ts", ROOT);
/** `deno fmt`'s line width, read from its one home so the emitter cannot disagree with it. */
const FMT_LINE_WIDTH = fmtLineWidth(await Deno.readTextFile(new URL("deno.json", ROOT)));

const readSource = (source: string) => Deno.readTextFile(new URL(source, TEMPLATES_DIR));

async function buildCoreEntries(m: Manifest): Promise<string[]> {
  const lines: string[] = [];
  for (const entry of m.core) {
    lines.push(coreEntry(entry, await readSource(entry.source), FMT_LINE_WIDTH));
  }
  return lines;
}

const BUNDLE_HEADER =
  `// THIS FILE IS GENERATED BY scripts/bundle-templates.ts — DO NOT EDIT BY HAND.
import type { CoreBundle } from "./domain/core_bundle.ts";
import type { TemplateFile } from "./domain/template.ts";
import type { ReleaseHistory } from "./domain/release_notes.ts";
`;

/** The generated module's text, from its parts. */
function bundleSource(version: string, core: string[], staticBlock: string, history: string) {
  return `${BUNDLE_HEADER}
export const TEMPLATES_VERSION = ${JSON.stringify(version)};

export const CORE_BUNDLE: CoreBundle = [
${core.join(",\n")},
];

export const HARNESS_STATIC: Record<string, Record<string, TemplateFile>> = {
${staticBlock},
};

export const RELEASE_HISTORY: ReleaseHistory = [
${history}];
`;
}

async function main() {
  const manifest = await readManifest(MANIFEST_PATH);
  await assertAllSourcesPresent(manifest, TEMPLATES_DIR);
  await assertManagedSectionsFenced(manifest.core, TEMPLATES_DIR);
  assertLinkEntries(manifest.core, manifest.harness_static);
  const core = await buildCoreEntries(manifest);
  const files = await staticFilesByHarness(manifest, readSource);
  const staticBlock = harnessStatic(files, FMT_LINE_WIDTH);
  const history = await readReleaseHistory(new URL(".specnaut/release/history/", ROOT));
  const historyText = releaseHistoryEntries(history, FMT_LINE_WIDTH);
  const src = bundleSource(manifest.version, core, staticBlock, historyText);
  await Deno.writeTextFile(OUTPUT_PATH, src);
  const output = relative(Deno.cwd(), fromFileUrl(OUTPUT_PATH));
  console.log(
    `Bundled ${manifest.core.length} core entries + ${manifest.harness_static.length} harness-specific → ${output}`,
  );
}

if (import.meta.main) await main();
