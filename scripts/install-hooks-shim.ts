// The text of the pre-commit shim `install-hooks.ts` writes: a regular file that
// finds the worktree at run time and execs its tracked hook, so a move of the
// checkout never leaves a dangling hook behind (#591).

/**
 * How the installer recognises a hook it wrote. A shim is a regular file, so
 * "is this ours?" is a content question — and it has to be answerable, because
 * refusing to touch a hook we installed ourselves is the second half of #591.
 */
export const SHIM_MARKER = "specnaut-managed pre-commit shim";

/**
 * The shim FAILS when it cannot find the hook. A shim that exec'd nothing and
 * exited 0 would reproduce the defect it exists to fix, one layer in: the
 * commit would pass because no check ran, which is the reading this whole
 * ticket is about.
 */
const SHIM = `#!/bin/sh
# ${SHIM_MARKER} — installed by \`deno task setup\`.
#
# Resolves the worktree at RUN time and runs the tracked hook from it, so the
# install survives a move or rename of the checkout. Do not edit this file;
# edit hooks/pre-commit, which is what actually runs.
#
# \`/bin/sh\` and \`set -eu\`, not bash: this file exists to be spawned by git on
# whatever the contributor is running, so it uses nothing outside POSIX. The
# hook it execs may be as bash-specific as it likes.
set -eu

root=$(git rev-parse --show-toplevel)
hook="$root/hooks/pre-commit"

if [ ! -x "$hook" ]; then
  echo "pre-commit: $hook is missing or not executable" >&2
  echo "  The shim found the worktree but no hook to run." >&2
  echo "  This is a broken install, not a pass — run \\\`deno task setup\\\`." >&2
  exit 1
fi

exec "$hook"
`;

/** The shim's text: what the installer writes, and compares an installed one against. */
export function shimContent(): string {
  return SHIM;
}
