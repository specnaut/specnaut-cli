#!/usr/bin/env bash
# PreToolUse(Edit|Write on Claude, apply_patch on Codex) — the one home of
# "which files are generated and may not be edited" (spec 036, plan § 5,
# FR-004). It used to warn and exit 0; the edit went through.
#
#   denied  .specnaut/installed.lock — `specnaut upgrade` owns it
#   gated   the gate's own switches: what the landing guard reads or runs,
#           the landing scripts and the hold they run (spec 048 § 8: an edit
#           could drop it), and what registers the guards —
#           .specnaut/workflow.yml, .specnaut/hooks/** (merge-approved.sh,
#           the hold's reader, included), .specnaut/scripts/bash/{merge-mode,
#           base-branch,merge-hold,land-feature,remove-spec}.sh,
#           .codex/hooks.json, .claude/settings.json and
#           .claude/settings.local.json (its `disableAllHooks` switches every
#           guard off). Held like a landing, through guard-merge's one arm,
#           approval_require: denied unless this turn's prompt said `merge`,
#           in Claude's ask modes too — a click on an edit prompt is not the
#           user's typed word — and, with it, Claude's prompt once where it
#           can ask.
#
# Decided by identity, never by text (§ 11 F5) — see _paths.sh, which reads
# the paths an edit names and resolves them; a patch from which no path can be
# read is refused.
#
# Usage: protect-generated.sh <claude|codex>   (payload on stdin)
case ${BASH_SOURCE[0]} in */*) HOOK_DIR=${BASH_SOURCE[0]%/*} ;; *) HOOK_DIR=. ;; esac
# shellcheck source=_guard.sh
. "$HOOK_DIR/_guard.sh" || { echo "specnaut: $HOOK_DIR/_guard.sh is missing — refusing" >&2; exit 2; }
# shellcheck source=_approval.sh
. "$HOOK_DIR/_approval.sh"
# shellcheck source=_paths.sh
. "$HOOK_DIR/_paths.sh" || guard_fail "_paths.sh is missing beside protect-generated.sh"
guard_init protect-generated "${1:-}" .tool_input.file_path .tool_input.notebook_path lines:.tool_input.command

paths_of_edit "${GF[0]}" "${GF[1]}" "${GF[2]}"
guard_root

denied="" gated=()
for p in "${EDIT_PATHS[@]}"; do
  t=$(paths_norm "$p")
  if paths_names "$t" .specnaut/installed.lock; then denied=$p; break; fi
  for g in .specnaut/workflow.yml .codex/hooks.json .claude/settings.json .claude/settings.local.json \
    .specnaut/scripts/bash/{merge-mode,base-branch,merge-hold,land-feature,remove-spec}.sh; do
    if paths_names "$t" "$g"; then gated+=("$g"); fi
  done
  if paths_names "$t" .specnaut/hooks under; then gated+=(".specnaut/hooks/"); fi
done

if [ -n "$denied" ]; then
  guard_fail "denied: $denied is .specnaut/installed.lock. .specnaut/installed.lock is generated by \`specnaut init\` / \`specnaut upgrade\`. Manual edits will be overwritten by the next upgrade. If you need to change the recorded harness or backend, re-run \`specnaut upgrade\` instead."
fi
[ ${#gated[@]} -gt 0 ] || guard_allow
approval_require merge \
  "editing ${gated[*]} changes how Specnaut gates landings on the base branch, so it needs the user" \
  "To let it through, reply \`merge\` (or \`/task merge\`) — a plain \"yes\" does not approve it."
