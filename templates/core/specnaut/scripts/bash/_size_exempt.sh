# shellcheck shell=bash
# Which changed files size-ratchet.sh leaves out without measuring them: sourced
# by it after _config.sh, every git call through its `git`.
#
#   size_exempt_init <limits> <lock>  splits the `exempt <glob>` lines of
#       config_size_limits' output: a `!` entry, `!` dropped, into
#       SIZE_EXEMPT_KEPT, any other into SIZE_EXEMPT_GLOBS; reads the lock's
#       entries, Specnaut's own files
#   size_exempt <path>  0 for `.specnaut/**`, a lock entry or a positive glob
#   size_generated_by_path <status> <old> <path>
#   size_generated_by_marker <status> <old> <path> <head prefix> <base>
#       0 when the file is generated by that signal, and print it as
#       `  generated: <path> (<why>)`; a marker refused is printed too
#
# Generated code needs no `exempt:` entry; either signal suffices. A path
# convention: a name the tools that write code give their output. A header
# marker: one of SIZE_GENERATED_PHRASES, in any case, in the first 5 lines of
# the first 8000 bytes (git's own sniff window). Never "do not edit" alone: a
# hand-written file says that too.
#
# A file the base already held keeps its answer: generated by marker only when
# the base copy carries one too, and a renamed file by name only when its old
# name was generated as well. A branch cannot exempt an existing file by
# renaming it or giving it a header. A `!` entry names files never generated, by
# name or by marker; it never undoes a positive glob, and stays out of
# config_exempt. A name holding a newline is never exempt and never generated.
# `specnaut scan` asks the same rules, from its own copy of both lists.

SIZE_EXEMPT_GLOBS=() SIZE_EXEMPT_KEPT=() SIZE_EXEMPT_MANAGED=""
SIZE_GENERATED_GLOBS=(
  "*/_generated/*" "*/__generated__/*" "*.gen.*" "*.generated.*" "*_generated.*"
  "*.pb.go" "*_pb2.py" "*_pb2_grpc.py" "*.g.dart" "*.freezed.dart"
  "*.lock" "*/package-lock.json" "*/npm-shrinkwrap.json" "*/pnpm-lock.yaml" "*/go.sum"
)
SIZE_GENERATED_PHRASES=(
  "@generated" "auto-generated" "autogenerated" "code generated" "generated file"
)
SIZE_GENERATED_WINDOW_BYTES=8000 SIZE_GENERATED_WINDOW_LINES=5

size_exempt_init() {
  local unit rest
  SIZE_EXEMPT_GLOBS=() SIZE_EXEMPT_KEPT=()
  while read -r unit rest; do
    [ "$unit" = exempt ] || continue
    case "$rest" in '!'*) SIZE_EXEMPT_KEPT+=("${rest#!}") ;; *) SIZE_EXEMPT_GLOBS+=("$rest") ;; esac
  done <<<"$1"
  SIZE_EXEMPT_MANAGED="$(config_lock_entries "$2")"
}

# grep would read a name holding a newline as several lines, any of which could
# name a managed file.
size_exempt() {
  case "$1" in *$'\n'*) return 1 ;; .specnaut/*) return 0 ;; esac
  if [ -n "$SIZE_EXEMPT_MANAGED" ] && printf '%s\n' "$SIZE_EXEMPT_MANAGED" | grep -Fxq -- "$1"; then
    return 0
  fi
  config_exempt "$1" ${SIZE_EXEMPT_GLOBS[@]+"${SIZE_EXEMPT_GLOBS[@]}"}
}

# 0 when generated defaults may apply to <path>: no newline, and no `!` entry.
_size_generated_open() {
  case "$1" in *$'\n'*) return 1 ;; esac
  ! config_exempt "$1" ${SIZE_EXEMPT_KEPT[@]+"${SIZE_EXEMPT_KEPT[@]}"}
}

_size_generated_name() { _size_generated_open "$1" && config_exempt "$1" "${SIZE_GENERATED_GLOBS[@]}"; }

size_generated_by_path() {
  _size_generated_name "$3" || return 1
  case "$1" in A*) ;; *) _size_generated_name "$2" || return 1 ;; esac
  echo "  generated: $3 (path convention)"
}

# 0 when <rev-spec>'s header holds a phrase. Read to a bounded window and matched
# in the shell, never piped into `grep -q`: under pipefail a reader that stops
# early turns a match into a SIGPIPE failure. Only A-Z is folded, byte by byte,
# and a NUL becomes \001, which no phrase holds: the shell would drop it, and
# join the bytes on either side into a phrase.
_size_generated_header() {
  local win
  win="$(git show "$1" 2>/dev/null | head -c "$SIZE_GENERATED_WINDOW_BYTES" |
    head -n "$SIZE_GENERATED_WINDOW_LINES" | LC_ALL=C tr 'A-Z\000' 'a-z\001')" || true
  (
    LC_ALL=C
    for phrase in "${SIZE_GENERATED_PHRASES[@]}"; do
      case "$win" in *"$phrase"*) exit 0 ;; esac
    done
    exit 1
  )
}

size_generated_by_marker() {
  _size_generated_open "$3" && _size_generated_header "$4$3" || return 1
  case "$1" in
    A*) echo "  generated: $3 (header marker, new file)" ;;
    *)
      if _size_generated_header "$5:$2"; then
        echo "  generated: $3 (header marker, already at the base)"
      else
        echo "  generated: $3 (header marker added - measured)"
        return 1
      fi
      ;;
  esac
}
