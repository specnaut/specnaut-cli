import { BINARY_SNIFF_BYTES } from "./binary_sniff.ts";
import { anyGlobTakes, compileGlobs } from "./case_glob.ts";

/**
 * What counts as generated code, which the size limits leave out with no `exempt:` entry (cli#798):
 * the TypeScript copy of `_size_exempt.sh`'s lists, which the ratchet sources in a project. A test
 * holds the two copies equal, and a differential fixture holds the two answers equal. Either signal
 * suffices; whether a `!` entry keeps a file measured is `size_exempt.ts`'s to decide.
 */

/**
 * The names code generators give their output, as bash `case` globs on `path` or `/path`. A
 * lockfile at any depth: a glob opening on `*` and a slash takes the root one too, as `/path`.
 */
// deno-fmt-ignore
export const GENERATED_GLOBS = [
  "*/_generated/*", "*/__generated__/*", "*.gen.*", "*.generated.*", "*_generated.*",
  "*.pb.go", "*_pb2.py", "*_pb2_grpc.py", "*.g.dart", "*.freezed.dart",
  "*.lock", "*/package-lock.json", "*/npm-shrinkwrap.json", "*/pnpm-lock.yaml", "*/go.sum",
] as const;

/**
 * Phrases a generator writes into its header, matched as substrings in any ASCII case. Literal, never
 * a pattern; and never "do not edit" alone, which a hand-written file says too.
 */
// deno-fmt-ignore
export const GENERATED_PHRASES = [
  "@generated", "auto-generated", "autogenerated", "code generated", "generated file",
] as const;

/** The header: the first lines of git's sniff window. A phrase deeper in a file is its prose. */
export const MARKER_LINES = 5;

const COMPILED = compileGlobs(GENERATED_GLOBS);

/** Unicode's control characters: C0 (a newline among them), DEL and C1. */
const CONTROL = /\p{Cc}/u;

/**
 * Whether the generated defaults may reach `path` at all, by name or by header. Not when it holds
 * a control character (cli#802): the ratchet prints a generated file's name raw, and an escape
 * sequence or a carriage return in it could rewrite the verdict a user reads.
 */
export function generatedMayApply(path: string): boolean {
  return !CONTROL.test(path);
}

/** Whether `path` is a generator's output by its name. */
export function generatedByPath(path: string): boolean {
  return generatedMayApply(path) && anyGlobTakes(COMPILED, path);
}

/**
 * Whether the header of a file's first bytes carries a phrase: the first `MARKER_LINES` lines
 * within `BINARY_SNIFF_BYTES`, read byte for byte as the ratchet's C-locale shell reads them, only
 * `A`-`Z` folded. A NUL is kept, so it breaks a phrase here as the ratchet's `\001` does there.
 */
export function hasGeneratedMarker(bytes: Uint8Array): boolean {
  let end = Math.min(bytes.length, BINARY_SNIFF_BYTES);
  for (let i = 0, seen = 0; i < end; i++) {
    if (bytes[i] === 0x0a && ++seen === MARKER_LINES) end = i;
  }
  let header = "";
  for (let i = 0; i < end; i++) {
    const b = bytes[i];
    header += String.fromCharCode(b >= 0x41 && b <= 0x5a ? b + 0x20 : b);
  }
  return GENERATED_PHRASES.some((phrase) => header.includes(phrase));
}
